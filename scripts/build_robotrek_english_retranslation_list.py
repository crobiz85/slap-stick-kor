def has_unresolved_engine_token(english: str) -> bool:
    # E3/E2 sequences are not Japanese text; they are unresolved English-ROM
    # engine tokens and must not be mistaken for ordinary letters.
    return bool(re.search(r"\[E[23]\]", english))


def load_mte_phrases() -> list[bytes]:
    """Load the USA ROM's E3 xx compressed English phrases."""
    raw = ROM.read_bytes()[MTE_START : MTE_END + 1]
    entries = raw.split(bytes((0xCC,)))
    if len(entries) != 256:
        raise ValueError(f"Expected 256 MTE phrases, found {len(entries)}")
    return entries


def expand_english_source(row: dict[str, str], phrases: list[bytes]) -> str:
    """Render the catalog record while expanding USA E3 xx tokens."""
    data = bytes.fromhex(row["raw_hex"])
    out: list[str] = []
    i = 0
    while i < len(data):
        value = data[i]
        if value == 0xE3 and i + 1 < len(data):
            out.append(phrases[data[i + 1]].decode("latin-1").replace("`", "’"))
            i += 2
        elif 0x20 <= value <= 0x7E:
            out.append(chr(value))
            i += 1
        elif value == 0xCD:
            out.append("\\n")
            i += 1
        elif value == 0xD1:
            out.append("\\f")
            i += 1
        elif value == 0xD0:
            out.append("[WIPE]")
            i += 1
        elif value == 0xD2:
            out.append("[WAIT]")
            i += 1
        elif value == 0xD7:
            out.append("[TOP]")
            i += 1
        elif value == 0xD8:
            out.append("[BOTTOM]")
            i += 1
        elif value == 0xD9:
            out.append("[TOP2]")
            i += 1
        elif value == 0xC3 and i + 1 < len(data):
            out.append({0x00: "[/HIGHLIGHT]", 0x02: "[YELLOW]", 0x03: "[PINK]"}.get(data[i + 1], f"[C3:{data[i + 1]:02X}]"))
            i += 2
        elif value == 0xC2 and i + 1 < len(data) and data[i + 1] == 0:
            out.append("[NAME]")
            i += 2
        elif value == 0xE0 and i + 1 < len(data):
            out.append(f"[SPEAKER:{data[i + 1]:02X}]")
            i += 2
        elif value == 0xDC:
            out.append("[DC]")
            i += 1
        else:
            out.append(f"[{value:02X}]")
            i += 1
    return "".join(out)


def expanded_row_source(row: dict[str, str], phrases: list[bytes]) -> str:
    """Dereference native CF wrappers before rendering their actual text."""
    indirect = INDIRECT_CF.get(row["record_id"])
    if not indirect:
        return expand_english_source(row, phrases)
    start = int(indirect[0], 16)
    payload = ROM.read_bytes()[start : start + indirect[1]]
    return expand_english_source({"raw_hex": payload.hex(" ")}, phrases)


def rough_size(text: str) -> int:
    """Conservative estimate: Hangul=2 bytes, visible ASCII=1, controls=1."""
    stripped = re.sub(r"\[[^\]]+\]", "X", text)
    return sum(2 if "가" <= char <= "힣" else 1 for char in stripped if char != "\n")


def load_rows() -> list[dict[str, str]]:
    with SOURCE.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader((line for line in handle if not line.startswith("#")), delimiter="\t"))


def write_tsv(rows: list[dict[str, str]], phrases: list[bytes]) -> None:
    columns = (
        "record_id",
        "region",
        "offset",
        "slot_bytes",
        "highlight",
        "english_source",
        "korean_retranslation_draft",
        "draft_bytes_rough",
        "space_check",
        "status",
    )
    with OUT_TSV.open("w", encoding="utf-8", newline="\n") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            draft = DRAFTS.get(row["record_id"], "")
            indirect = INDIRECT_CF.get(row["record_id"])
            slot = indirect[1] if indirect else int(row["length_without_terminator"])
            size = rough_size(draft) if draft else ""
            english_source = expanded_row_source(row, phrases)
            unresolved = has_unresolved_engine_token(english_source)
            if indirect:
                status = "간접 대사-CF 대상 번역"
            elif row["record_id"] in NON_DIALOGUE_IDS:
                status = "대사 아님-삽입 제외"
            elif row["record_id"] in MIXED_DATA_IDS:
                status = "혼합 데이터-대사 번역 완료/삽입 경계 재분석" if draft else "혼합 데이터-경계 재분석"
            else:
                status = "번역 완료-공간 초과" if draft and isinstance(size, int) and size > slot else ("번역 완료-예비 적합" if draft else ("영문 토큰 복원 필요" if unresolved else "번역 대기"))
            check = ("검토 필요" if isinstance(size, int) and size > slot else "예비 적합") if draft else ""
            writer.writerow(
                {
                    "record_id": row["record_id"],
                    "region": row["region"],
                    "offset": f"{row['start_offset']}→{indirect[0]}" if indirect else row["start_offset"],
                    "slot_bytes": slot,
                    "highlight": "yes" if row["has_highlight"] == "True" else "no",
                    "english_source": english_source,
                    "korean_retranslation_draft": draft,
                    "draft_bytes_rough": size,
                    "space_check": check,
                    "status": status,
                }
            )


def write_txt(rows: list[dict[str, str]], phrases: list[bytes]) -> None:
    with OUT_TXT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("Robotrek (USA) 영문판 기준 재번역 목록\n")
        handle.write("일본판 대사·일본판 참조 번역은 포함하지 않았습니다.\n")
        handle.write("영문판 E3 압축 구문은 USA 롬의 원문표에서 복원했습니다.\n\n")
        for row in rows:
            draft = DRAFTS.get(row["record_id"], "")
            english_source = expanded_row_source(row, phrases)
            unresolved = has_unresolved_engine_token(english_source)
            indirect = INDIRECT_CF.get(row["record_id"])
            if indirect:
                status = "간접 대사-CF 대상 번역"
            elif row["record_id"] in NON_DIALOGUE_IDS:
                status = "대사 아님-삽입 제외"
            elif row["record_id"] in MIXED_DATA_IDS:
                status = "혼합 데이터-대사 번역 완료/삽입 경계 재분석" if draft else "혼합 데이터-경계 재분석"
            else:
                status = "번역 완료-공간 초과" if draft and rough_size(draft) > (indirect[1] if indirect else int(row["length_without_terminator"])) else ("번역 완료-예비 적합" if draft else ("영문 토큰 복원 필요" if unresolved else "번역 대기"))
            handle.write(
                f"[{row['record_id']}] {row['region']} {row['start_offset']}"
                f"{'→' + indirect[0] if indirect else ''} "
                f"공간={indirect[1] if indirect else row['length_without_terminator']}바이트 "
                f"강조={'예' if row['has_highlight'] == 'True' else '아니오'}\n"
            )
            handle.write(f"영문: {english_source}\n")
            if draft:
                handle.write(f"번역안: {draft}\n")
            else:
                handle.write(f"상태: {status}\n")
            handle.write("\n")


def main() -> None:
    rows = load_rows()
    phrases = load_mte_phrases()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_tsv(rows, phrases)
    write_txt(rows, phrases)
    print(f"rows={len(rows)}")
    print(f"drafts={len(DRAFTS)}")
    print(f"tsv={OUT_TSV}")
    print(f"txt={OUT_TXT}")


if __name__ == "__main__":
    main()
